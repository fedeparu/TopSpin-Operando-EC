"""Create entirely synthetic standard-format EC and Bruker examples.

No uploaded or measured experimental values are used. Uses only Python stdlib.
Run from the repository: python scripts/generate_examples.py
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import math
from pathlib import Path
import struct
import zipfile


def parameter_file(path: Path, values: dict):
    path.write_text("##TITLE= ENTIRELY SYNTHETIC EC-NMR example\n##JCAMPDX= 5.0\n" + "".join(f"##${key}= {value}\n" for key, value in values.items()) + "##END=\n", encoding="ascii")


def generate(destination: Path, archive: Path | None = None):
    destination.mkdir(parents=True, exist_ok=True)
    ec = destination / "synthetic.mpt"
    rows = []
    charge = 0.0
    previous_current = 0.0
    for t in range(721):
        current = 0.3 if t < 360 else -0.3
        if t:
            charge += (current + previous_current) / 2 / 3600
        potential = 3.0 + 1.2 * (t / 360 if t <= 360 else (720 - t) / 360)
        rows.append(f"{t}\t{potential:.8f}\t{current:.8f}\t{charge:.10f}")
        previous_current = current
    ec.write_text("EC-Lab ASCII FILE\nNb header lines : 5\nComments : ENTIRELY SYNTHETIC; no experimental data\nAcquisition started on : 01/01/2025 00:00:00 UTC (synthetic ground truth)\ntime/s\tEwe/V\tI/mA\t(Q-Qo)/mA.h\n" + "\n".join(rows) + "\n", encoding="ascii")
    nmr = destination / "bruker"
    epoch = int(datetime(2025, 1, 1, tzinfo=timezone.utc).timestamp())
    for acquisition in range(6):
        exp = nmr / str(acquisition + 1)
        processed = exp / "pdata" / "1"
        processed.mkdir(parents=True, exist_ok=True)
        parameter_file(exp / "acqus", {"NUC1": "<7Li>", "SFO1": 155.5, "PULPROG": "<zg>", "NS": 8, "DS": 0, "TD": 1024, "SW_h": 31100, "PARMODE": 0, "DATE_START": epoch + acquisition * 120, "DATE": epoch + acquisition * 120 + 90})
        parameter_file(processed / "procs", {"SI": 512, "SF": 155.5, "SW_p": 31100, "OFFSET": 100, "BYTORDP": 0, "DTYPP": 0, "NC_proc": 0, "XDIM": 512})
        (processed / "title").write_text(f"ENTIRELY SYNTHETIC 7Li example; acquisition {acquisition+1}\n", encoding="ascii")
        values = []
        for i in range(512):
            ppm = 100 - i * 200 / 512
            peak = 100000 * math.exp(-0.5 * ((ppm - acquisition * 0.5) / 2.5) ** 2)
            evolving_peak = (10000 + acquisition * 12000) * math.exp(-0.5 * ((ppm - 25) / 4) ** 2)
            baseline = 100 * math.sin(i * 0.3 + acquisition)
            values.append(round(peak + evolving_peak + baseline))
        (processed / "1r").write_bytes(struct.pack("<512i", *values))
    (destination / "PROVENANCE.txt").write_text("ENTIRELY SYNTHETIC. Generated by scripts/generate_examples.py using analytic peaks and a triangular potential. No measured data or uploaded spectra were copied.\nGround truth: EC and NMR begin together at synthetic UTC2025-01-01T00:00:00. Six NMR acquisitions begin every120s, duration90s.\n", encoding="ascii")
    if archive:
        archive.parent.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(archive, "w", compression=zipfile.ZIP_DEFLATED) as output:
            for source in sorted(nmr.rglob("*")):
                if source.is_file():
                    output.write(source, source.relative_to(destination))
    return ec, nmr


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--destination", type=Path, default=Path("examples/synthetic"))
    parser.add_argument("--zip", type=Path, default=Path("work/synthetic-bruker.zip"))
    args = parser.parse_args()
    ec, nmr = generate(args.destination, args.zip)
    print(f"Synthetic EC: {ec}\nSynthetic Bruker series: {nmr}\nNMR upload ZIP: {args.zip}")


if __name__ == "__main__":
    main()
